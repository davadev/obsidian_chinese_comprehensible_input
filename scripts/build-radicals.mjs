#!/usr/bin/env node
/**
 * Build script: reads the Kangxi radical of every CJK Unified Ideograph (U+4E00..U+9FFF) from Unicode's Unihan database
 * (`kRSUnicode`) and emits src/dictionary/radicalMap.generated.ts, two small base64 tables the plugin looks radicals up in.
 *
 * Source: https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip  (file Unihan_IRGSources.txt, property kRSUnicode)
 * License: Unicode License v3 (permissive; attribution kept in NOTICE.md).
 *
 * kRSUnicode is "radical.strokes" with an apostrophe after the radical number when the character uses the SIMPLIFIED form
 * of that radical (讠 for 言, 钅 for 金…). A few characters list a second radical-stroke value; the first is the
 * conventional one and is the one used. Only the radical number and that simplified flag are imported: no readings,
 * definitions or variants.
 *
 * Needs `unzip` on the PATH (to read one file out of the archive without a dependency).
 *
 * Run: `npm run build:radicals`
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, "..", "src", "dictionary", "radicalMap.generated.ts");
const URL_ZIP = "https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip";
const FIRST = 0x4e00;
const LAST = 0x9fff;
const COUNT = LAST - FIRST + 1;

const dir = mkdtempSync(join(tmpdir(), "cci-unihan-"));
const zip = join(dir, "Unihan.zip");
const res = await fetch(URL_ZIP);
if (!res.ok) throw new Error(`HTTP ${res.status} for ${URL_ZIP}`);
writeFileSync(zip, Buffer.from(await res.arrayBuffer()));
const text = execFileSync("unzip", ["-p", zip, "Unihan_IRGSources.txt"], { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

const radical = new Uint8Array(COUNT);
const simplified = new Uint8Array(Math.ceil(COUNT / 8));
let seen = 0;
for (const line of text.split("\n")) {
  const m = /^U\+([0-9A-F]+)\tkRSUnicode\t(\d+)('*)\.(-?\d+)/.exec(line);
  if (!m) continue;
  const cp = parseInt(m[1], 16);
  if (cp < FIRST || cp > LAST) continue;
  const n = Number(m[2]);
  if (n < 1 || n > 214) throw new Error(`radical out of range: ${line}`);
  radical[cp - FIRST] = n;
  if (m[3]) simplified[(cp - FIRST) >> 3] |= 1 << ((cp - FIRST) & 7);
  seen++;
}
if (seen < 20000) throw new Error(`only ${seen} characters parsed; the file layout changed?`);

const b64 = (u8) => Buffer.from(u8).toString("base64");
const src = `// GENERATED by scripts/build-radicals.mjs from Unicode's Unihan kRSUnicode (Unicode License v3). Do not edit.
// One byte per code point from U+${FIRST.toString(16).toUpperCase()} (the Kangxi radical number, 0 = unknown), and one bit per
// code point saying the character uses the simplified form of its radical.
export const RADICAL_FIRST_CODE_POINT = 0x${FIRST.toString(16)};
export const RADICAL_NUMBERS_B64 = "${b64(radical)}";
export const RADICAL_SIMPLIFIED_B64 = "${b64(simplified)}";
`;
writeFileSync(OUT_PATH, src);
console.log(`wrote ${OUT_PATH}: ${seen} characters, ${src.length} bytes`);
